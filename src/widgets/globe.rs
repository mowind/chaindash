/// Orthographic projection of (lat, lng) onto the unit disk, given a view
/// center. Returns `None` for the back hemisphere (z <= 0).
fn project(
    lat: f64,
    lng: f64,
    center_lat: f64,
    center_lng: f64,
) -> Option<(f64, f64)> {
    project_with_depth(lat, lng, center_lat, center_lng).map(|(x, y, _)| (x, y))
}

fn project_with_depth(
    lat: f64,
    lng: f64,
    center_lat: f64,
    center_lng: f64,
) -> Option<(f64, f64, f64)> {
    let delta_lng = (lng - center_lng).to_radians();
    let (sin_lat, cos_lat) = lat.to_radians().sin_cos();
    let (sin_center, cos_center) = center_lat.to_radians().sin_cos();

    let x = cos_lat * delta_lng.sin();
    let y = cos_center * sin_lat - sin_center * cos_lat * delta_lng.cos();
    let z = sin_center * sin_lat + cos_center * cos_lat * delta_lng.cos();

    if z <= 0.0 {
        None
    } else {
        Some((x, y, z))
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ColorMode {
    TrueColor,
    Ansi256,
    Ansi16,
    Monochrome,
}

#[derive(Debug, Clone, Copy)]
struct GlobePalette {
    land: Color,
    trail: Color,
    peers: [Color; 4],
    background: Color,
    border: Color,
    title: Color,
    stats: Color,
}

fn color_mode() -> ColorMode {
    let term = env::var("TERM").unwrap_or_default();
    let color_term = env::var("COLORTERM").unwrap_or_default();
    color_mode_from_values(env::var_os("NO_COLOR").is_some(), &term, &color_term)
}

fn color_mode_from_values(
    no_color: bool,
    term: &str,
    color_term: &str,
) -> ColorMode {
    if no_color {
        return ColorMode::Monochrome;
    }

    let term = term.to_ascii_lowercase();
    if term == "dumb" {
        return ColorMode::Monochrome;
    }

    let color_term = color_term.to_ascii_lowercase();
    if color_term.contains("truecolor")
        || color_term.contains("24bit")
        || term.contains("direct")
        || term.contains("truecolor")
    {
        ColorMode::TrueColor
    } else if term.contains("256color") {
        ColorMode::Ansi256
    } else {
        ColorMode::Ansi16
    }
}

